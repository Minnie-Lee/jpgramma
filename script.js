/* ───────── 작문 엔진 ───────── */
function createCompose(root, { getPool, label, onExit, emptyText }) {
  let score = 0, total = 0, item, ex, lastId = null, busy = false;
  root.innerHTML = `
    <div class="run-head">
      ${onExit ? '<button class="btn sm lav" data-act="exit">목록</button>' : ''}
      <span class="run-title">${label}</span>
      <span class="score">통과 <b data-r="score">0</b> / <span data-r="total">0</span></span>
    </div>
    <div class="memo tape-lav" data-r="card">
      <span class="q-tag">한국어 → 일본어</span>
      <p class="inst">아래 문장을 일본어로 원고지에 써 주세요<small lang="ja">日本語で書いてみよう（Ctrl+Enterで提出）</small></p>
      <div class="c-kr" data-r="kr"></div>
      <button class="hint-btn" data-r="hintbtn">💡 쓸 문법 힌트 보기</button>
      <div><span class="hint" data-r="hint" hidden></span></div>
      <div class="genko" data-r="genko"><textarea lang="ja" data-r="input" aria-label="작문 입력" autocomplete="off" spellcheck="false"></textarea></div>
      <div class="btns" data-r="actions"><button class="btn lav" data-r="skip">다른 문장</button><button class="btn solid" data-r="submit">제출하고 모범 답안 보기</button></div>
      <div data-r="result" hidden>
        <div class="model"><div class="model-l"><span lang="ja">おてほん</span><span data-r="play"></span></div><div class="ex-jp" lang="ja" data-r="model"></div></div>
        <p class="self">모범 답안과 비교해서 스스로 채점해 주세요</p>
        <div class="btns"><button class="btn matcha" data-r="ok">맞았어요</button><button class="btn sora" data-r="ng">틀렸어요</button></div>
      </div>
    </div>`;
  const r = k => root.querySelector(`[data-r="${k}"]`);
  if (onExit) root.querySelector('[data-act="exit"]').onclick = onExit;

  function next() {
    busy = false;
    const pool = getPool();
    if (!pool.length) { r('card').innerHTML = ''; r('card').appendChild(doneBox(emptyText || '쓸 문장이 없어요.', onExit, '목록으로')); return; }
    const cands = pool.length > 1 ? pool.filter(p => p.id !== lastId) : pool;
    item = pick(cands); lastId = item.id; ex = pick(item.exList);
    r('kr').textContent = ex.kr;
    r('hint').hidden = true;
    r('hint').innerHTML = `<b lang="ja">${item.grammar}</b>　${item.meaning}`;
    r('hintbtn').hidden = false;
    r('genko').querySelectorAll('.stamp').forEach(m => m.remove());
    r('input').value = ''; r('input').disabled = false;
    r('actions').hidden = false;
    r('result').hidden = true;
    setTimeout(() => r('input').focus({ preventScroll: true }), 50);
  }
  function submit() {
    const v = r('input').value.trim();
    if (!v) { toast('원고지에 먼저 써 주세요'); r('input').focus(); return; }
    r('input').disabled = true;
    r('actions').hidden = true;
    r('hintbtn').hidden = true; r('hint').hidden = false;
    r('model').innerHTML = ex.jpLearn;
    r('play').innerHTML = ''; r('play').appendChild(playBtn(ex.cleanJp));
    r('result').hidden = false;
    r('result').scrollIntoView({ behavior: 'smooth', block: 'nearest' });
  }
  function grade(ok) {
    if (busy) return; busy = true;
    total++; if (ok) score++;
    r('score').textContent = score; r('total').textContent = total;
    updateScore(item.id, ok, 'compose');
    stamp(r('genko'), ok, true);
    toast(ok ? '통과! 도장 꾹' : '복습 목록에 넣었어요');
    r('genko').scrollIntoView({ behavior: 'smooth', block: 'center' });
    setTimeout(() => { next(); window.scrollTo({ top: 0, behavior: 'smooth' }); }, 1000);
  }
  r('hintbtn').onclick = () => { r('hint').hidden = false; r('hintbtn').hidden = true; };
  r('skip').onclick = next;
  r('submit').onclick = submit;
  r('input').onkeydown = e => { if (e.key === 'Enter' && (e.ctrlKey || e.metaKey)) submit(); };
  r('ok').onclick = () => grade(true);
  r('ng').onclick = () => grade(false);
  next();
}

let composeReady = false;
function composeStart() {
  if (composeReady) return;
  composeReady = true;
  createCompose($('#compose-root'), { getPool: () => grammarDB, label: '랜덤 작문' });
}

